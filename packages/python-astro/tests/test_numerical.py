def test_events_analytic_nodes():
    # Existing analytic ellipse in OEM km/km/s; Earth inertial equatorial z=0, UTC.
    case=V['events']; start=datetime.fromtimestamp(case['START']/1000,timezone.utc)
    period=case['PERIOD_SECONDS']; t=np.arange(0,2*period+1,10.); omega=2*np.pi/period
    angle=omega*t+case['PHASE']; A,B,C=case['A'],case['B'],case['C']
    states=np.column_stack((A*np.cos(angle),B*np.sin(angle),C*np.sin(angle),
        -A*omega*np.sin(angle),B*omega*np.cos(angle),C*omega*np.cos(angle)))/1000
    epochs=[(start+timedelta(seconds=float(s))).isoformat(timespec='milliseconds').replace('+00:00','') for s in t]
    context=obj('PCE.PCEEvaluationContext',CENTRAL_BODY_ID=399,GRAVITATIONAL_PARAMETER=3.986004418e14,
        EQUATORIAL_RADIUS_M=6378137.,FLATTENING=1/298.257223563)
    request=obj('EVL.EVLEventLocationRequest',LOCATOR_CLASS=5,CONTEXT=context,
        SCAN_START_EPOCH=epochs[0],SCAN_STOP_EPOCH=epochs[-1],EPOCH_TIME_SYSTEM='UTC',
        SCAN_STEP_SECONDS=30.,REFINEMENT_TOLERANCE_SECONDS=1e-9)
    report=astro.events(epochs,states,request)
    assert report['STATUS']==1, report['ERROR_MESSAGE']
    actual=report['EVENTS']; assert len(actual)==4
    errors=[]
    for i,event in enumerate(actual):
        # datetime truncates submicroseconds; parse fraction independently for ns report precision.
        date,fraction=event['START_EPOCH'].rstrip('Z').split('.')
        sec=(datetime.fromisoformat(date).replace(tzinfo=timezone.utc)-start).total_seconds()+float('0.'+fraction)
        expected=(np.pi-case['PHASE'])/omega+i*period/2
        errors.append(abs(sec-expected))
    measure('Events analytic four nodes',max(errors),'s',1e-3)


def test_conjunction_socrates_three_events():
    # CelesTrak SOCRATES fixed GP window; UTC JD, scalar miss km/speed km/s.
    records={r['NORAD_CAT_ID']:r for rows in V['conjunctionGp'].values() for r in rows}
    def jd(iso):return datetime.fromisoformat(iso.rstrip('Z')).replace(tzinfo=timezone.utc).timestamp()/86400+2440587.5
    refs=V['conjunction']['conjunctions']; start=min(jd(r['EPOCH']) for r in records.values())-.05
    result=astro.conjunction_assessment(list(records.values()),start_jd=start,
        duration_days=max(7.,max(jd(r['tca']) for r in refs)-start+.25),threshold_km=5.,threads=1)
    events=result['conjunctions'];assert len(events)==len(refs)
    errors=[]
    for reference in refs:
        event=next(e for e in events if {e['obj1Norad'],e['obj2Norad']}=={reference['obj1_norad'],reference['obj2_norad']})
        errors.append((abs(event['tcaJd']-jd(reference['tca']))*86400,
            abs(event['minRangeKm']-reference['min_range_km'])*1000,
            abs(event['relSpeedKms']-reference['rel_speed_kms'])*1000))
    measure('Conjunction SOCRATES max TCA',max(e[0] for e in errors),'s',.010)
    measure('Conjunction SOCRATES max miss',max(e[1] for e in errors),'m',5.)
    measure('Conjunction SOCRATES max speed',max(e[2] for e in errors),'m/s',5.)
