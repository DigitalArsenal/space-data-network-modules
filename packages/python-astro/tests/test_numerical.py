from datetime import datetime, timedelta, timezone
import json
from pathlib import Path
import numpy as np
import pytest
import spacedatanetwork_astro as astro
from spacedatanetwork_astro._codec import obj

V = json.loads((Path(__file__).parent / 'fixtures/module-vectors.json').read_text())


def measure(name, error, unit, tolerance):
    print(f'MEASURE {name}: error={error:.16g} {unit}; tolerance={tolerance:.16g} {unit}')
    assert error <= tolerance


def omm_record(source):
    fields = {'noradId':'NORAD_CAT_ID','objectName':'OBJECT_NAME','objectId':'OBJECT_ID',
              'epoch':'EPOCH','meanMotion':'MEAN_MOTION','eccentricity':'ECCENTRICITY',
              'inclination':'INCLINATION','raan':'RA_OF_ASC_NODE','argPericenter':'ARG_OF_PERICENTER',
              'meanAnomaly':'MEAN_ANOMALY','bstar':'BSTAR','meanMotionDot':'MEAN_MOTION_DOT',
              'meanMotionDdot':'MEAN_MOTION_DDOT'}
    return {fields[k]:v for k,v in source.items()}


def test_sgp4_vallado_radius():
    # Vallado TEME radius is invariant under the module's ECEF rotation. UTC JD.
    case = V['sgp4']
    state = astro.sgp4(omm_record(case['VALLADO_OMM']), [case['VALLADO_TARGET_JD']])[0]
    measure('SGP4 Vallado radius', abs(np.linalg.norm(state[:3])-case['VALLADO_TEME_POSITION_MAGNITUDE_METERS']), 'm', .01)


def test_hpop_tudat_six_samples():
    # Tudat inertial two-body fixture, km/km/s, J2000 TDB JD; original RK4 envelope.
    case = V['hpop']; samples = case['twoBody']['samples']; first=samples[0]
    errors=[]
    for sample in samples:
        state=astro.hpop(first['positionKm'], first['velocityKmPerSec'], case['epochJulianDate'],
                         case['epochJulianDate']+sample['timeSeconds']/86400.)
        errors.append((np.linalg.norm(state.position-sample['positionKm']), np.linalg.norm(state.velocity-sample['velocityKmPerSec'])))
    measure('HPOP Tudat six-sample max position', max(e[0] for e in errors), 'km', 5e-4)
    measure('HPOP Tudat six-sample max velocity', max(e[1] for e in errors), 'km/s', 5e-7)


