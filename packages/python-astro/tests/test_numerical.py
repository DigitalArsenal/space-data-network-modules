def test_lambert_closed_form():
    # Existing JS analytic circular quarter orbit; GCRF km/km/s, UTC label only.
    case=V['lambert']; mu=case['mu']; radius=case['radius']
    tof=np.pi/2*np.sqrt(radius**3/mu); speed=np.sqrt(mu/radius)
    actual=astro.lambert_izzo([radius,0,0],[0,radius,0],tof,mu_km3_s2=mu)
    assert actual['STATUS']==0
    err=max(np.max(np.abs(actual['SINGLE']['V1']-[0,speed,0])),np.max(np.abs(actual['SINGLE']['V2']-[-speed,0,0])))
    measure('Lambert circular quarter orbit',err,'km/s',1e-6)


def test_access_orekit_elevation_vectors():
    # Same Orekit inverse topocentric tuples; ACW PIV reports max elevation.
    # Constant ECEF samples isolate geometry; TT JD is explicit in ACW.
    errors=[]
    for case in V['access']['vectors']:
        az,el,r=case['azimuthRad'],case['elevationRad'],case['rangeM']
        pos=[6378137+r*np.sin(el),r*np.cos(el)*np.sin(az),r*np.cos(el)*np.cos(az)]
