const table=JSON.parse(fs.readFileSync(new URL('../data/parameters.json',import.meta.url)));
const parameter=(model,name)=>table.find(p=>p.model===model&&p.parameter===name).value;
const bytes=fs.readFileSync(new URL('../dist/isomorphic/module.wasm',import.meta.url));

// Independent CLOSED-FORM sphere solution, Heng et al. (2021),
// doi:10.1038/s41550-021-01444-7 Eqs.(8)-(11). Runtime uses surface quadrature.
// Table 1 medians from Heng & Li doi:10.3847/2041-8213/abe872 are inputs,
// not outputs generated by the module. Units: dimensionless albedo; static
// homogeneous sphere, angles radians, no epoch or rotating longitude.
function analyticHeng(nm,a) {
  const model=`jupiter:heng2021:${nm}nm`,w=parameter(model,'w'),f=parameter(model,'f');
  const g1=parameter(model,'g1'),g2=parameter(model,'g2');
  const e=(1-Math.sqrt(1-w))/(1+Math.sqrt(1-w));
  const P=a=>f*(1-g1*g1)/(1+g1*g1+2*g1*Math.cos(a))**1.5+
    (1-f)*(1-g2*g2)/(1+g2*g2+2*g2*Math.cos(a))**1.5;
  const geometric=w/8*(P(0)-1)+e/2+e*e/6+e**3/24;
  if(a===0)return geometric;
  const rho=a=>P(a)-1+(1+e)**2*(2-e)**2/4;
  const linear=e/2*(1+e)**2*(2-e),quadratic=e*e*(1+e)**2;
  const c=Math.cos(a/2),s=Math.sin(a/2),logCot=Math.log(1/Math.tan(a/4));
  return geometric*(12*rho(a)*(1-s*s/c*logCot)+
    16*linear*(Math.sin(a)+(Math.PI-a)*Math.cos(a))/Math.PI+
    9*quadratic*(-1+5/3*c*c+Math.tan(a/2)*s**3*logCot))/(12*rho(0)+16*linear+6*quadratic);
}
function interpolate(x,points) {
  const j=Math.min(points.length-2,Math.max(0,points.findIndex(p=>p[0]>=x)-1));
  const [a,fa]=points[j],[b,fb]=points[j+1];
  return fa+(fb-fa)*(x-a)/(b-a);
}
function spectralIntegral(phase) {
  const n=parameter('solar:calspec2015','sample_count');
  const solar=Array.from({length:n},(_,i)=>[parameter('solar:calspec2015',`wavelength_${i}`),parameter('solar:calspec2015',`irradiance_${i}`)]);
  const filter=Array.from({length:24},(_,i)=>[470+10*i,parameter('band:bessell1990:V',`response_${470+10*i}`)]);
  const albedo=filter.map(([nm])=>[nm,analyticHeng(nm,phase)]);
  const knots=[...new Set([...solar,...filter].map(([nm])=>nm).filter(nm=>nm>=470&&nm<=700))].sort((a,b)=>a-b);
  // Simpson integrates the piecewise cubic F*T*albedo exactly. Unlike the
  // runtime, integrate the disk analytically FIRST, then integrate wavelength.
  const integrand=(x,planet)=>interpolate(x,solar)*interpolate(x,filter)*(planet?interpolate(x,albedo):1);
  const integral=planet=>knots.slice(1).reduce((sum,b,i)=>{
    const a=knots[i];return sum+(b-a)/6*(integrand(a,planet)+4*integrand((a+b)/2,planet)+integrand(b,planet));
  },0);
  return integral(true)/integral(false);
}

test('synthetic Johnson V matches analytic sphere plus independent spectral Simpson integration',async t=>{
  const h=await createBrowserModuleHarness({wasmSource:bytes,surface:'direct'});t.after(()=>h.destroy());
  // Synthetic geometry in meters and au. Solar V=-26.75 from Colina et al.
  // (1996), doi:10.1086/118016 Tables 2/3. Energy response is Bessell (1990)
  // doi:10.1086/132749 Table 2, not a photon-throughput curve.
  const angles=[0,.02,.3,.8,Math.PI/2,2,130*Math.PI/180];
  const q={model:'jupiter:heng2021:V',phase_rad:angles,radius_m:1000,sun_distance_au:2,observer_distance_m:1e8};
  const actual=await invoke(h,'disk_photometry',q);
  for(let i=0;i<angles.length;i++) {
    const expected=spectralIntegral(angles[i]);
    // 2e-7 relative budgets numerical integration of the limb/terminator.
    // This is implementation accuracy, not the 0.1 mag observational gate.
    assert.ok(Math.abs(actual.disk_albedo[i]/expected-1)<2e-7,`${angles[i]}: ${actual.disk_albedo[i]} vs ${expected}`);
    const magnitude=-26.75-2.5*Math.log10(expected*(1000/1e8/2)**2);
    assert.ok(Math.abs(actual.apparent_magnitude[i]-magnitude)<3e-7);
  }
  assert.match(actual.band,/Johnson V/);
  const farther=await invoke(h,'disk_photometry',{...q,sun_distance_au:4,observer_distance_m:2e8});
  for(let i=0;i<angles.length;i++)assert.ok(Math.abs(farther.solar_flux_ratio[i]/actual.solar_flux_ratio[i]-1/16)<1e-15);
  for(const change of [{solar_magnitude:-26.75},{surface_albedo:.5},{phase_rad:[141*Math.PI/180]}])
    assert.notEqual((await h.invoke(encodeRequest('disk_photometry',{...q,...change}))).statusCode,0);
});
