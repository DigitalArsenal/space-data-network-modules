#!/usr/bin/env python3
"""Generate src/xp_hansen_series.inc: the SPEC 6.1 resonant terms of each class
and Kaula's eccentricity functions G_lpq(e) as their Maclaurin polynomials
(SPEC 6.4: e^|q|, e^(|q|+2), ... up to e^26 for even q and e^27 for odd q),
with exact rational coefficients rounded once to double.

G_lpq(e) = X_k^{n,m}(e), n = -(l+1), m = l-2p, k = l-2p+q, the Hansen
coefficient (1/2pi) Int (r/a)^n exp(i m nu) exp(-i k M) dM. With
beta = e/(1+sqrt(1-e^2)), z = exp(iE):
  r/a = (1-beta z)(1-beta/z)/(1+beta^2), exp(i nu) = z (1-beta/z)/(1-beta z),
  exp(-i k M) = z^-k exp((k e/2)(z - 1/z)), dM = (r/a) dE,
so X = (1+beta^2)^l * sum_j a_(j+q) b_j with
  A(z) = (1-beta z)^(-2(l-p)) exp(k e z/2) = sum a_i z^i,
  B(w) = (1-beta w)^(-2p) exp(-k e w/2) = sum b_j w^j.
"""
from fractions import Fraction as F
from math import comb, factorial
import sys

D = 27  # e^26 for even q, e^27 for odd q (SPEC 6.4)

def mul(a, b):
    r = [F(0)] * (D + 1)
    for i, x in enumerate(a):
        if x:
            for j in range(D + 1 - i):
                if b[j]:
                    r[i + j] += x * b[j]
    return r

def scal(a, s):
    return [x * s for x in a]

def add(a, b):
    return [x + y for x, y in zip(a, b)]

def inv(a):
    r = [F(0)] * (D + 1)
    r[0] = 1 / a[0]
    for n in range(1, D + 1):
        r[n] = -sum(a[i] * r[n - i] for i in range(1, n + 1)) / a[0]
    return r

def power(a, k):
    r = [F(0)] * (D + 1); r[0] = F(1)
    for _ in range(k):
        r = mul(r, a)
    return r

def gbinom_neg(a, s):  # coefficient of x^s in (1-x)^(-a)
    if a == 0:
        return 1 if s == 0 else 0
    return comb(a + s - 1, s)

E = [F(0)] * (D + 1); E[1] = F(1)
ETA = [F(0)] * (D + 1)
for j in range(D // 2 + 1):  # sqrt(1-e^2)
    c = F(1)
    for t in range(j):
        c *= (F(1, 2) - t) / (t + 1)
    ETA[2 * j] = c * (-1) ** j
ONE = [F(0)] * (D + 1); ONE[0] = F(1)
BETA = mul(E, inv(add(ONE, ETA)))
BETA_POW = [ONE]
for _ in range(D + 1):
    BETA_POW.append(mul(BETA_POW[-1], BETA))
ONE_PLUS_B2 = add(ONE, mul(BETA, BETA))

def series(l, p, q):
    m = l - 2 * p
    k = m + q
    ke2 = scal(E, F(k, 2))
    ke2_pow = [ONE]
    for _ in range(D + 1):
        ke2_pow.append(mul(ke2_pow[-1], ke2))
    def coef(i, a, sign):
        r = [F(0)] * (D + 1)
        for s in range(i + 1):
            c = gbinom_neg(a, s)
            if c:
                t = scal(mul(BETA_POW[s], ke2_pow[i - s]), F(c * sign ** (i - s), factorial(i - s)))
                r = add(r, t)
        return r
    total = [F(0)] * (D + 1)
    j = max(0, -q)
    while 2 * j + q <= D:
        total = add(total, mul(coef(j + q, 2 * (l - p), 1), coef(j, 2 * p, -1)))
        j += 1
    return mul(power(ONE_PLUS_B2, l), total)

# SPEC 6.1 (closed-modules main ef9e2169): the terms (l, m, p, q) of each class, k = l - 2p + q.
def class_terms(cls):
    out = []
    if cls == 1:  # k = m, |q| <= 4
        for l, m, ps in [(2, 2, range(3)), (3, 1, range(4)), (3, 2, range(3)), (3, 3, range(3)), (4, 1, range(4)),
                         (4, 2, range(4)), (4, 3, range(3)), (4, 4, range(3))]:
            out += [(l, m, p, m - l + 2 * p) for p in ps if abs(m - l + 2 * p) <= 4]
    elif cls == 2:  # k = m/2, every p, -4 <= q <= 7
        for l, m in [(2, 2), (3, 2), (4, 2), (4, 4), (5, 2), (5, 4)]:
            out += [(l, m, p, m // 2 - l + 2 * p) for p in range(l + 1) if -4 <= m // 2 - l + 2 * p <= 7]
    elif cls == 3:  # k = 1, m = 3, -4 <= q <= 5
        for l, ps in [(3, range(4)), (4, range(5)), (5, range(5)), (6, range(1, 6))]:
            out += [(l, 3, p, 1 - l + 2 * p) for p in ps if -4 <= 1 - l + 2 * p <= 5]
    elif cls == 4:  # k = 2, m = 3, q <= 6
        for l, ps in [(3, range(4)), (4, range(5)), (5, range(5)), (6, range(6))]:
            out += [(l, 3, p, 2 - l + 2 * p) for p in ps if 2 - l + 2 * p <= 6]
    return out
CLASSES = {c: class_terms(c) for c in (1, 2, 3, 4)}
assert [len(CLASSES[c]) for c in (1, 2, 3, 4)] == [27, 29, 19, 20]
NAMES = {1: "one_day", 2: "half_day", 3: "eight_hour", 4: "sixteen_hour"}

unique = []
for cls in sorted(CLASSES):
    for (l, m, p, q) in CLASSES[cls]:
        if (l, p, q) not in unique:
            unique.append((l, p, q))

out = ["// Generated by tools/hansen_series.py. Do not edit.",
       "// SPEC 6.1 resonant terms per class and Kaula's G_lpq(e) = X_(l-2p+q)^(-(l+1), l-2p)(e)",
       "// as Maclaurin polynomials (SPEC 6.4): G = e^|q| * sum_j c[j] e^(2j), up to e^26 (even q)",
       "// or e^27 (odd q), exact rational coefficients rounded once to double.",
       "struct HansenSeries {",
       "  int8_t l, p, q, lead, count;",
       "  double c[14];",
       "};",
       "inline constexpr HansenSeries kHansen[] = {"]
for (l, p, q) in unique:
    s_ = series(l, p, q)
    lead = abs(q)
    assert all(s_[i] == 0 for i in range(lead)), (l, p, q)
    assert all(s_[i] == 0 for i in range(lead + 1, D + 1, 2)), (l, p, q)
    cs = [s_[lead + 2 * j] for j in range((D - lead) // 2 + 1)]
    body = ", ".join(repr(float(c)) for c in cs)
    out.append(f"    {{{l}, {p}, {q}, {lead}, {len(cs)}, {{{body}}}}},")
out.append("};")
out.append(f"inline constexpr int kHansenCount = {len(unique)};")
out.append("struct ResonantTerm {")
out.append("  int8_t l, m, p, q, k, hansen;")
out.append("};")
for cls in sorted(CLASSES):
    items = ", ".join(f"{{{l}, {m}, {p}, {q}, {l - 2 * p + q}, {unique.index((l, p, q))}}}" for (l, m, p, q) in CLASSES[cls])
    out.append(f"inline constexpr ResonantTerm kTerms_{NAMES[cls]}[] = {{{items}}};")
out.append("")
sys.stdout.write("\n".join(out) + "\n")
