// Builds vectors/vectors.json: Tier B anchors for the propagator ABI (plugin_propagate) of propagator/sgp4-xp.
//   node vectors/tools/build-vectors.mjs          writes vectors/vectors.json
//   node vectors/tools/build-vectors.mjs --check  exits 1 when the file on disk differs
// Expected states come from the US Space Force library through its own, unmodified Emscripten runtime
// (third_party/ussf-sgp4/Sgp4Prop.xp.js), TEME km and km/s, turned to the ABI's ECEF metres by GMST (IAU 1982, the
// SDK conformance runner's own gmstRadians) with the -omega x r velocity term. The module wraps the same library, so
// these anchors catch defects of the adapter, the shim, the ABI record mapping (BSTAR = BTERM, MEAN_MOTION_DDOT =
// AGOM), units and frames; they are not an independent check of the SGP4-XP theory.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { battery, omm, referenceLibrary } from '../../tests/lib/tle.mjs';
import { pathToFileURL } from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');
const sdkRoot = path.join(root, 'node_modules/space-data-module-sdk');
// The conformance runner's own GMST, so the anchors and the adjudication share one frame definition.
const { gmstRadians } = await import(pathToFileURL(path.join(sdkRoot, 'src/conformance/twoBodyReference.js')).href);
const OMEGA = 7.292115146706979e-5;
const KIND = ['leo', 'sun-synchronous', 'meo', 'geo', 'heo'];
const MINUTES = [0, 90, 1440];

// The epoch exactly as the two-line text states it: Julian date of 0 January of the year plus the day field.
const julianOfLine = (l1) => { const yy = Number(l1.slice(18, 20)); const y = yy < 57 ? 2000 + yy : 1900 + yy; return Date.UTC(y, 0, 1) / 86400000 + 2440587.5 - 1 + Number(l1.slice(20, 32)); };
function ecef(rKm, vKmS, jd) {
  const t = gmstRadians(jd), c = Math.cos(t), s = Math.sin(t);
  const r = [c * rKm[0] + s * rKm[1], -s * rKm[0] + c * rKm[1], rKm[2]].map((x) => x * 1000);
  const vr = [c * vKmS[0] + s * vKmS[1], -s * vKmS[0] + c * vKmS[1], vKmS[2]].map((x) => x * 1000);
  return { r, v: [vr[0] + OMEGA * r[1], vr[1] - OMEGA * r[0], vr[2]] };
}

const lib = await referenceLibrary();
const cases = [];
for (const set of battery(10, 20261012).filter((s) => s.type === 4)) {
  const f = omm(set.lines);
  const epochJd = julianOfLine(set.lines[0]);
  const elements = {
    epochJd, meanMotionRevPerDay: f.meanMotion, eccentricity: f.eccentricity, inclinationDeg: f.inclination,
    raOfAscNodeDeg: f.raan, argOfPericenterDeg: f.argPerigee, meanAnomalyDeg: f.meanAnomaly,
    bstar: f.bterm, meanMotionDdot: f.agom, noradCatId: f.norad,
  };
  const states = lib.propagate(set.lines, MINUTES);
  if (!states) throw new Error(`the library refused ${set.lines[0]}`);
  states.forEach((st, i) => {
    if (st.error !== 0) throw new Error(`library error ${st.error} for ${set.lines[0]} at +${MINUTES[i]} min`);
    const jd = epochJd + MINUTES[i] / 1440;
    const { r, v } = ecef(st.r, st.v, jd);
    cases.push({
      id: `${KIND[set.kind]}-xp@+${MINUTES[i]}min`, tier: 'B', operation: 'plugin_propagate',
      note: `SGP4-XP (ephemeris type 4) ${KIND[set.kind]} set of the test battery (seed 20261012): ${set.lines[0]}`,
      params: { elements, julianDate: jd },
      expect: { 'position.0': r[0], 'position.1': r[1], 'position.2': r[2], 'velocity.0': v[0], 'velocity.1': v[1], 'velocity.2': v[2], epoch: jd, reference_frame: 3, flags: 1 },
      band: { position: { abs: 0.5, rel: 0 }, velocity: { abs: 5e-4, rel: 0 }, time: { abs: 1e-9, rel: 0 } },
      source: { kind: 'reference-library', derivation: 'US Space Force Sgp4Prop 9.1.1.0 (XP build) through its own Emscripten runtime, TEME; TEME -> ECEF by GMST (IAU 1982) with -omega x r.', generator: 'vectors/tools/build-vectors.mjs', twoLine: set.lines },
    });
  });
}

const corpus = {
  '//': 'GENERATED by vectors/tools/build-vectors.mjs. DO NOT HAND-EDIT. Provenance for every row is in vectors/PROVENANCE.md.',
  schemaVersion: 1,
  conformance: {
    model: 'SGP4-XP (US Space Force Sgp4Prop 9.1.1.0): perturbed mean-element theory; two-body invariants do not apply',
    units: 'SI throughout: metres, metres/second, Julian days, degrees on input; BSTAR carries BTERM (m^2/kg) and MEAN_MOTION_DDOT carries AGOM (m^2/kg)',
    outputFrame: 'ECEF (ORBPRO_FRAME_ECEF = 3): TEME turned by GMST (IAU 1982), no polar motion',
  },
  tolerancePolicy: 'fail <=> |observed - expected| > abs + rel * |expected|',
  invariants: [],
  cases,
};
const text = `${JSON.stringify(corpus, null, 1)}\n`;
const out = path.join(root, 'vectors/vectors.json');
if (process.argv.includes('--check')) {
  if (!fs.existsSync(out) || fs.readFileSync(out, 'utf8') !== text) { console.error('vectors/vectors.json differs from the generator'); process.exit(1); }
  console.log(`vectors/vectors.json matches (${cases.length} cases)`);
} else {
  fs.writeFileSync(out, text);
  console.log(`wrote ${cases.length} cases`);
}
