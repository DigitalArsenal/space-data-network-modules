// ---- SDS frames ($NST, $PNV) built with the flatbuffers runtime, field slots per the SDS schemas ---------------------
function nstFrame(peers) {
  const b = new flatbuffers.Builder(256);
  const rows = peers.map((p) => { const s = b.createString(p); b.startObject(30); b.addFieldOffset(0, s, 0); return b.endObject(); });
  b.startVector(4, rows.length, 4); for (let i = rows.length - 1; i >= 0; i--) b.addOffset(rows[i]); const v = b.endVector();
  b.startObject(4); b.addFieldOffset(0, v, 0); b.finish(b.endObject(), '$NST'); return b.asUint8Array().slice();
}
// entries: {publisher, receivedAtMs, verified, keySource (1 IdentityRecord, 2 PeerIdentifier, 3 OperatorTrust, 4 SelfAsserted)}
function pnvFrame(entries) {
  const b = new flatbuffers.Builder(256);
  const rows = entries.map((e) => {
    const s = b.createString(e.publisher); b.startObject(19);
    b.addFieldOffset(1, s, 0); b.addFieldInt64(9, BigInt(e.receivedAtMs), 0n); b.addFieldInt8(12, e.verified ? 1 : 0, 0); b.addFieldInt8(15, e.keySource, 0);
    return b.endObject();
  });
  b.startVector(4, rows.length, 4); for (let i = rows.length - 1; i >= 0; i--) b.addOffset(rows[i]); const v = b.endVector();
  b.startObject(4); b.addFieldOffset(2, v, 0); b.finish(b.endObject(), '$PNV'); return b.asUint8Array().slice();
}
// $APR (size-prefixed) -> {method, path, route, params}
function readApr(context) {
  assert.equal(new DataView(context.buffer, context.byteOffset).getUint32(0, true), context.length - 4);
  assert.equal(identifierOf(context.subarray(4)), '$APR');
  const bb = new flatbuffers.ByteBuffer(Uint8Array.from(context.subarray(4)));
  const root = bb.readInt32(0), field = (t, slot) => { const o = bb.__offset(t, 4 + 2 * slot); return o ? t + o : 0; };
  const s = (t, slot) => { const o = bb.__offset(t, 4 + 2 * slot); return o ? bb.__string(t + o) : ''; };
  const params = {}; const po = field(root, 6);
  if (po) { const vec = bb.__vector(po), n = bb.__vector_len(po); for (let i = 0; i < n; i++) { const t = bb.__indirect(vec + 4 * i); params[s(t, 0)] = s(t, 1); } }
  const mo = field(root, 2);
  return { method: ['', 'GET', 'HEAD', 'POST', 'PUT', 'PATCH', 'DELETE'][mo ? bb.readUint8(mo) : 0], path: s(root, 3), route: s(root, 4), params };
}

