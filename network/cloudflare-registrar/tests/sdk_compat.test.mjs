// A Cloudflare "List DNS Records" answer (https://developers.cloudflare.com/api/resources/dns/subresources/records/methods/list/).
const record = (extra = {}) => ({ id: recordId, zone_id: zoneId, zone_name: 'spacedatanetwork.org', name: `${label}.spacedatanetwork.org`, type: 'A',
  content: '167.172.219.213', proxiable: true, proxied: true, ttl: 1, settings: {}, meta: {}, comment: `sdn-peer:${label}`, tags: [],
  created_on: '2026-10-01T00:00:00.000000Z', modified_on: '2026-10-01T00:00:00.000000Z', ...extra });
const page = (records, { page = 1, totalPages = 1, totalCount = records.length, status = 200, zone = zoneId, retrievedMs = NOW_MS, success = true } = {}) => ({
  portId: 'dns_records', typeRef: TYPE.HRSP,
  payload: encodeHttpResponse({ url: `${API}/zones/${zone}/dns_records?per_page=5000&page=${page}`, status, retrievedMs,
    body: new TextEncoder().encode(JSON.stringify({ success, errors: [], messages: [], result: records,
      result_info: { page, per_page: 5000, count: records.length, total_count: totalCount, total_pages: totalPages } })) }),
});
const peersIn = (peers = []) => ({ portId: 'peers', typeRef: TYPE.NST, payload: nstFrame(peers) });
const verified = (publisher = peerId, receivedAtMs = 1000_000, keySource = 1, ok = true) => ({ publisher, receivedAtMs, verified: ok, keySource });
const pnvIn = (entries = [verified()]) => ({ portId: 'verifications', typeRef: TYPE.PNV, payload: pnvFrame(entries) });
const peer = (extra = {}) => ({ peer_id: peerId, included: true, origin_verified: true, public_artifacts_only: true, origin_ipv4: '167.172.219.213', ...extra });
const config = (extra = {}) => ({ cloudflare_zone_id: zoneId, cloudflare_zone_name: 'spacedatanetwork.org', peers: [peer()], ...extra });
const owned = { managed_records: [{ label, record_id: recordId }] };

async function harness(t, cfg) {
  const host = await createBrowserModuleHarness({ wasmSource: wasm, manifest, surface: 'direct', hostOptions: { config: cfg } });
  t.after(() => host.destroy()); return host;
}
async function invoke(t, cfg, { records = [], pages, peers = [], pnv } = {}) {
  const host = await harness(t, cfg);
  return host.invoke({ methodId: 'plan', inputs: [...(pages ?? [page(records)]), peersIn(peers), pnv ?? pnvIn()] });
}
async function plan(t, cfg, inputs) {
  const result = await invoke(t, cfg, inputs); assert.equal(result.statusCode, 0, result.errorMessage);
  const actions = result.outputs.filter((o) => o.portId === 'requests').map((o) => {
    assert.equal(o.typeRef?.fileIdentifier ?? 'HREQ', 'HREQ');
    const r = decodeHttpRequest(o.payload);
    return { ...r, apr: readApr(r.context), json: r.body.length ? JSON.parse(new TextDecoder().decode(r.body)) : null };
  });
  const nodes = result.outputs.filter((o) => o.portId === 'status').map((o) => decodeFlowNotice(o.payload));
  return { actions, nodes };
}

