test("every signed committed artifact is owner-signed, except the exact dev-signed list", () => {
  const list = JSON.parse(fs.readFileSync(DEV_SIGNED_LIST, "utf8"));
  assert.equal(list.revokedSignerPublicKeyHex, DEV_SIGNER_PUBLIC_KEY_HEX);
  const listed = new Set(list.artifacts);
  assert.equal(listed.size, list.artifacts.length, "the dev-signed list has duplicates");
  const tracked = execFileSync("git", ["ls-files", "-z", "--", "*.wasm"], { cwd: REPO_ROOT, encoding: "utf8" }).split("\0").filter(Boolean);
  const devSigned = [];
  const foreign = [];
  for (const rel of tracked) {
    const signer = signerOf(new Uint8Array(fs.readFileSync(path.join(REPO_ROOT, rel))));
    if (!signer) continue;
    if (signer.publicKeyHex === OWNER_SIGNER_PUBLIC_KEY_HEX) continue;
    if (signer.publicKeyHex === DEV_SIGNER_PUBLIC_KEY_HEX) devSigned.push(rel);
    else foreign.push(`${rel} (${signer.publicKeyHex}, ${signer.keyId})`);
  }
  assert.deepEqual(foreign, [], "committed artifacts signed by a key that is neither the owner's nor the listed dev key");
  assert.deepEqual(devSigned.sort(), [...listed].sort(), "scripts/lib/dev-signed-artifacts.json must list exactly the dev-signed artifacts");
});

