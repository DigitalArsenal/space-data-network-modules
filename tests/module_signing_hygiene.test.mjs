// Build scripts another live graph task holds; each drops off this list when
// its holder lands the same fail-closed signer (scripts/lib/module-signing-key.mjs).
const PENDING_DEV_FIXTURE_REFERENCES = new Map([
  // A gate file (needs a task with a gate_edit reason). It hands the fixture
  // path to census REBUILDS only, and every signer now refuses that key, so
  // those rebuilds fail closed; the patch that gives them a throwaway key instead
  // waits for its gate task.
  ["scripts/check-artifact-reproducibility.mjs", "gate file: needs a gate_edit task"],
]);

test("no build, release or signing script resolves the SDK dev signing fixture", () => {
  const tracked = execFileSync("git", ["ls-files", "-z", "--", "*.mjs", "*.js", "*.cjs", "*.sh"], { cwd: REPO_ROOT, encoding: "utf8" })
    .split("\0")
    .filter(Boolean)
    .filter((rel) => !/(^|\/)(node_modules|tests?|docs)\//.test(rel) && !/\.test\.m?js$/.test(rel));
  const offenders = [];
  for (const rel of tracked) {
    if (PENDING_DEV_FIXTURE_REFERENCES.has(rel)) continue;
    const text = fs.readFileSync(path.join(REPO_ROOT, rel), "utf8");
    // Any mention, quoted or not, outside a comment line: a split string is
    // caught by the signer rule below.
    const code = text.split("\n").filter((line) => !/^\s*(\/\/|\*|\/\*)/.test(line)).join("\n");
    if (/dev-module-signing-keypair/.test(code)) offenders.push(rel);
  }
  assert.deepEqual(offenders, [], "these resolve the public dev fixture as a signing key");
});

// Every script that signs a module goes through the fail-closed key handling
// (scripts/lib/module-signing-key.mjs): it imports that library, or it is listed
// here with the guard it relies on, and that guard imports the library.
const SIGNERS_GUARDED_ELSEWHERE = new Map([
  ["flows/supplemental-omm/scripts/release.mjs", "flows/supplemental-omm/nodes/signing.mjs"],
]);

test("every script that calls signModuleArtifact or protectModuleArtifact uses the fail-closed signing library", () => {
  const tracked = execFileSync("git", ["ls-files", "-z", "--", "*.mjs", "*.js", "*.cjs"], { cwd: REPO_ROOT, encoding: "utf8" })
    .split("\0")
    .filter(Boolean)
    .filter((rel) => !/(^|\/)(node_modules|tests?|docs)\//.test(rel) && !/\.test\.m?js$/.test(rel))
    .filter((rel) => !/(^|\/)dist\//.test(rel) && rel !== "scripts/lib/module-signing-key.mjs");
  const importsLibrary = (rel) => /module-signing-key\.mjs["']/.test(fs.readFileSync(path.join(REPO_ROOT, rel), "utf8"));
  const unguarded = [];
  for (const rel of tracked) {
    const text = fs.readFileSync(path.join(REPO_ROOT, rel), "utf8");
    if (!/\b(signModuleArtifact|protectModuleArtifact)\s*\(/.test(text)) continue;
    if (importsLibrary(rel)) continue;
    const guard = SIGNERS_GUARDED_ELSEWHERE.get(rel);
    if (guard && importsLibrary(guard)) continue;
    unguarded.push(rel);
  }
  assert.deepEqual(unguarded, [], "these sign without the fail-closed key handling");
});

