test("publish-sign signs as the configured publisher: PNM and MBL signers are the mnemonic's keys", { timeout: 120_000 }, async (t) => {
  const { pkg, walletEnv, script } = publishSignLayout(t, BIP39_TEST_VECTOR);
  const run = spawnSync(process.execPath, [script], {
    encoding: "utf8",
    env: { ...envWithout(), SDN_MODULE_SIGNING_WALLET_ENV: walletEnv },
  });
  assert.equal(run.status, 0, run.stderr);
  const { getWasmWallet } = await import("space-data-module-sdk/utils/wasm-crypto");
  const wallet = await getWasmWallet();
  const signingKey = wallet.getSigningKey(wallet.hdkey.fromSeed(wallet.mnemonic.toSeed(BIP39_TEST_VECTOR)), 0, 0, 0);
  const pnmSigner = Buffer.from(signingKey.publicKey).toString("hex");
  assert.match(run.stdout, new RegExp(`pnm signer \\(secp256k1\\) publicKeyHex=${pnmSigner}`));
  const lib = await import(SIGNING_LIB);
  const ed25519 = lib.ed25519PublicKeyHexFromSeed(Buffer.from(signingKey.privateKey).toString("hex"));
  const signed = new Uint8Array(fs.readFileSync(path.join(pkg, "dist", "isomorphic", "module.wasm")));
  assert.equal(signerOf(signed).publicKeyHex, ed25519);
  assert.equal((await verifyModuleArtifact(signed, { trustedPublicKeys: [ed25519], requireSignature: true })).verified, true);
});

