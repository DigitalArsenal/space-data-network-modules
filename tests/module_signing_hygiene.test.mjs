// MODULE SIGNING HYGIENE (security audit SEC-005 build side, SEC-035).
//
// 1. A build signs with the key SDM_MODULE_SIGNING_KEYPAIR_PATH names, or it
//    refuses. It never falls back to the SDK's dev fixture (keyId
//    sdm-dev-test-2026, public key cf4625…, seed published in a public repo),
//    and it refuses that signer even when it is named explicitly.
// 2. No build or signing script in this repository resolves the dev fixture.
// 3. Every committed artifact that carries a signature is signed by the owner's
//    release key, except the dev-signed ones listed in
//    scripts/lib/dev-signed-artifacts.json, and that list is exact. So is its
//    list of tests that still trust the dev signer (they move to the owner key
//    in the re-sign commit).
// 4. A publisher mnemonic that is public (the SDN dev-admin wallet, security
//    audit SEC-007) is refused by publish-sign, matched by its PUBLIC account
//    xpub and signing key.
//
// Every key used here is generated by the test and thrown away. The dev
// fixture itself is never opened: refusing it is proved by its PUBLIC key.

