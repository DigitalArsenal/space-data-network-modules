function throwawayKeypair(overrides = {}) {
  const { privateKey, publicKey } = crypto.generateKeyPairSync("ed25519");
  return {
    keyId: "test-throwaway",
    publicKeyHex: Buffer.from(publicKey.export({ format: "jwk" }).x, "base64url").toString("hex"),
    privateKeySeedHex: Buffer.from(privateKey.export({ format: "jwk" }).d, "base64url").toString("hex"),
    ...overrides,
  };
}

function writeJson(file, value) {
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, `${JSON.stringify(value)}\n`, { mode: 0o600 });
}

function scratch(t) {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), "modules-signing-hygiene-"));
  t.after(() => fs.rmSync(dir, { recursive: true, force: true }));
  return dir;
}

// The stack layout sign-module-artifact.mjs used to search, rebuilt in a
// scratch dir: <root>/repos/main-packages/space-data-network-modules/<group>/<pkg>/dist/isomorphic/module.wasm,
// with a throwaway key PLANTED where the SDK's dev fixture would sit. Signing
// with the planted key is exactly the silent fallback.
function stackLayout(t) {
  const root = scratch(t);
  const repo = path.join(root, "repos", "main-packages", "space-data-network-modules");
  const artifact = path.join(repo, "analysis", "fixture", "dist", "isomorphic", "module.wasm");
  fs.mkdirSync(path.dirname(artifact), { recursive: true });
  fs.writeFileSync(artifact, MINIMAL_WASM);
  fs.symlinkSync(path.join(REPO_ROOT, "node_modules"), path.join(repo, "node_modules"));
  const planted = throwawayKeypair({ keyId: "planted-dev-fixture" });
  for (const fixture of [
    path.join(root, "repos", "ancillary-packages", "space-data-module-sdk", "test", "support", "dev-module-signing-keypair.json"),
    path.join(repo, "..", "space-data-module-sdk", "test", "support", "dev-module-signing-keypair.json"),
  ]) {
    writeJson(fixture, planted);
  }
  return { root, artifact, planted };
}

function envWithout(...names) {
  const env = { ...process.env };
  for (const name of [
    "SDM_MODULE_SIGNING_KEYPAIR_PATH",
    "SDN_MODULE_SIGNING_KEYPAIR",
    "SDN_MODULE_SIGNING_MNEMONIC",
    "SDN_MODULE_SIGNING_WALLET_ENV",
    ...names,
  ]) {
    delete env[name];
  }
  return env;
}

function runSign(artifact, env) {
  return spawnSync(process.execPath, [SIGN_SCRIPT, artifact], { encoding: "utf8", env });
}

function signerOf(bytes) {
  const record = extractPublicationRecordCollection(bytes);
  const entry = record?.mbl?.entries?.find(
    (candidate) =>
      String(candidate.role).toLowerCase() === "signature" ||
      candidate.entryId === "signature" ||
      candidate.sectionName === "sds.signature",
  );
  if (!entry) return null;
  const payload = JSON.parse(new TextDecoder().decode(new Uint8Array(entry.payload)));
  return { publicKeyHex: String(payload.publicKeyHex).toLowerCase(), keyId: payload.keyId ?? null };
}

