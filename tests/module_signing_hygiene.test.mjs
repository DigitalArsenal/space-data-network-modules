test("the leaked dev-admin publisher (SEC-007) is denylisted by values derived from its public xpub alone", async () => {
  const lib = await import(SIGNING_LIB);
  const { getWasmWallet } = await import("space-data-module-sdk/utils/wasm-crypto");
  const wallet = await getWasmWallet();
  const leaked = lib.REVOKED_PUBLISHER_IDENTITIES.find((entry) => entry.accountXpub === LEAKED_DEV_ADMIN_XPUB);
  assert.ok(leaked, "the leaked dev-admin xpub must be on the publisher denylist");
  // m/44'/0'/0' -> /0/0 is non-hardened: the signer follows from the xpub.
  const account = wallet.hdkey.fromXpub(LEAKED_DEV_ADMIN_XPUB);
  const derived = Buffer.from(account.deriveChild(0).deriveChild(0).publicKey()).toString("hex");
  assert.equal(leaked.signingPublicKeyHex, derived);
  assert.equal(derived, LEAKED_DEV_ADMIN_SIGNER);
  assert.throws(() => lib.assertPublisherNotRevoked({ accountXpub: LEAKED_DEV_ADMIN_XPUB }), (error) => error.code === "revoked_publisher");
  assert.throws(() => lib.assertPublisherNotRevoked({ signingPublicKeyHex: derived.toUpperCase() }), (error) => error.code === "revoked_publisher");
  assert.throws(
    () => lib.assertProtectedByPublisher({ signingPublicKeyHex: derived }, { signingPublicKeyHex: derived }),
    (error) => error.code === "revoked_publisher",
  );
  // A publisher that is not revoked resolves, and its identity is the test vector's.
  const identity = await lib.resolvePublisherIdentity(wallet, BIP39_TEST_VECTOR);
  assert.equal(identity.accountXpub, BIP39_TEST_VECTOR_XPUB);
  assert.equal(identity.signingPublicKeyHex, BIP39_TEST_VECTOR_SIGNER);
});

// ---- the package builds that used to fall back to the dev fixture -----------

// A package copied into the stack layout (stackLayout plants a throwaway key
// where the SDK's dev fixture used to be found), with this repo's scripts/.
function packageLayout(t, rel) {
  const layout = stackLayout(t);
  const repo = path.join(layout.root, "repos", "main-packages", "space-data-network-modules");
  fs.cpSync(path.join(REPO_ROOT, rel), path.join(repo, rel), {
    recursive: true,
    filter: (source) => !/[\\/](node_modules|\.build|\.emcache|deps)$/.test(source),
  });
  fs.symlinkSync(path.join(REPO_ROOT, "scripts"), path.join(repo, "scripts"));
  return { ...layout, repo, pkg: path.join(repo, rel) };
}

function snapshotDist(dir) {
  const out = new Map();
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { recursive: true, withFileTypes: true })) {
    if (entry.isFile()) {
      const file = path.join(entry.parentPath ?? entry.path, entry.name);
      out.set(path.relative(dir, file), crypto.createHash("sha256").update(fs.readFileSync(file)).digest("hex"));
    }
  }
  return out;
}

for (const rel of ["basilisk/runtime", "data-source/gps-source", "data-source/oneweb-source"]) {
  test(`${rel} build refuses, before compiling, with no key configured or with the revoked dev signer`, { timeout: 120_000 }, (t) => {
    const { root, pkg } = packageLayout(t, rel);
    const dist = path.join(pkg, "dist");
    const before = snapshotDist(dist);
    const claimsDevKey = path.join(root, "claims-dev-key.json");
    writeJson(claimsDevKey, throwawayKeypair({ publicKeyHex: DEV_SIGNER_PUBLIC_KEY_HEX, keyId: "renamed" }));
    for (const [label, env, expected] of [
      ["nothing configured", envWithout(), /SDM_MODULE_SIGNING_KEYPAIR_PATH is not set/],
      ["dev signer by path", { ...envWithout(), SDM_MODULE_SIGNING_KEYPAIR_PATH: claimsDevKey }, /revoked module signer/],
      // basilisk never read the legacy name: for it the key is simply not set.
      ["dev signer by the legacy name", { ...envWithout(), SDN_MODULE_SIGNING_KEYPAIR: claimsDevKey }, /revoked module signer|SDM_MODULE_SIGNING_KEYPAIR_PATH is not set/],
    ]) {
      const run = spawnSync(process.execPath, [path.join(pkg, "build.mjs")], { cwd: pkg, encoding: "utf8", env, timeout: 100_000 });
      assert.notEqual(run.status, 0, `${rel} (${label}) built:\n${run.stdout}`);
      assert.match(run.stderr, expected, `${rel} (${label}) did not refuse for the signing key:\n${run.stderr}`);
      assert.doesNotMatch(run.stdout, /\$ |em\+\+|clang|Compil/i, `${rel} (${label}) started compiling before refusing`);
      assert.deepEqual(snapshotDist(dist), before, `${rel} (${label}) changed dist/`);
      assert.equal(fs.existsSync(path.join(pkg, ".build")), false, `${rel} (${label}) created a build dir`);
    }
  });
}

