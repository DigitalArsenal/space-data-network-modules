test("sign-module-artifact signs with the configured key, and only that key", async (t) => {
  const { root, artifact, planted } = stackLayout(t);
  const keypair = throwawayKeypair();
  const keypairPath = path.join(root, "release-keypair.json");
  writeJson(keypairPath, keypair);
  const run = runSign(artifact, { ...envWithout(), SDM_MODULE_SIGNING_KEYPAIR_PATH: keypairPath });
  assert.equal(run.status, 0, run.stderr);
  assert.ok(!run.stdout.includes(keypair.privateKeySeedHex), "the seed must never be printed");
  const signed = new Uint8Array(fs.readFileSync(artifact));
  assert.deepEqual(signerOf(signed), { publicKeyHex: keypair.publicKeyHex, keyId: keypair.keyId });
  const verified = await verifyModuleArtifact(signed, { trustedPublicKeys: [keypair.publicKeyHex], requireSignature: true });
  assert.equal(verified.verified, true);
  await assert.rejects(
    verifyModuleArtifact(signed, { trustedPublicKeys: [planted.publicKeyHex], requireSignature: true }),
    /untrusted_signer|not in the trusted signer set/,
  );
});

