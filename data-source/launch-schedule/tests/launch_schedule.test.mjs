// Fixture: a slice of the real Launch Library 2 response to
// GET /2.3.0/launches/upcoming/?mode=normal&limit=100 recorded 2026-09-28,
// one launch per NET precision class (second, minute, day, month, quarter,
// half year, year). Expected windows are calendar arithmetic on the recorded
// NETs, computed by hand below; nothing is generated by the module under test.
// Typed contracts 1.0: the plan is a TimerTick + node CONFIG (plugin.getConfig, SDS $PIV) -> one HttpRequest whose
// CONTEXT is a size-prefixed IngestRequest; parse takes the HttpResponse echoing it.
const root = process.env.SPACE_DATA_STANDARDS_ROOT ?? path.dirname(createRequire(import.meta.url).resolve('spacedatastandards.org/package.json'));
const require = createRequire(path.join(root, 'package.json'));
const { ByteBuffer } = require('flatbuffers');
const { LDM } = await import(pathToFileURL(path.join(root, 'lib/js/LDM/main.js')));
const manifest = JSON.parse(fs.readFileSync(CORE.manifest));
const recordedBytes = fs.readFileSync(new URL('./fixtures/ll2-upcoming-2026-09-28.json', import.meta.url));
const recorded = JSON.parse(recordedBytes);
const URL_100 = 'https://ll.thespacedevs.com/2.3.0/launches/upcoming/?format=json&mode=normal&limit=100';
const CITATION = 'Launch data from Launch Library 2 by The Space Devs (https://thespacedevs.com), free access tier.';

async function core(t, config = nodeConfig()) { return harness(t, { ...CORE, config }); }
const planned = (h) => h.invoke({ methodId: 'plan_launches', inputs: [tick()] });
async function plan(t, config) {
  const h = await core(t, config);
  const result = await planned(h);
  assert.equal(result.statusCode, 0, result.errorMessage);
  return decodeHttpRequest(result.outputs[0].payload);
}
const parse = (h, context, body = recorded, status = 200, opts) => h.invoke({ methodId: 'parse_launches', inputs: [httpResponse(context, body, status, opts)] });
const out = (result, port) => result.outputs.find((f) => f.portId === port);
function readJob(context) {
  assert.equal(identifierOf(context.subarray(4)), 'INGQ');
  return decodeIngestRequest(context.slice(4));
}
// A job as a size-prefixed IngestRequest (to hand parse a tampered plan).
function sizePrefixed(job) {
  const bytes = encodeIngestRequest(job);
  const framed = new Uint8Array(bytes.length + 4);
  new DataView(framed.buffer).setUint32(0, bytes.length, true);
  framed.set(bytes, 4);
  return framed;
}
function records(result) {
  const bytes = out(result, 'records').payload, rows = [];
  for (let offset = 0; offset < bytes.length;) {
    const size = new DataView(bytes.buffer, bytes.byteOffset + offset, 4).getUint32(0, true) + 4;
    const frame = bytes.slice(offset, offset + size);
    assert.equal(Buffer.from(frame.slice(8, 12)).toString(), '$LDM');
    rows.push(LDM.getSizePrefixedRootAsLDM(new ByteBuffer(frame)).unpack());
    offset += size;
  }
  return rows;
}

test('the artifact satisfies the SDK contract with typed ports only', async () => {
  const report = await validateArtifactWithStandards({ wasmPath: CORE.wasm, manifest, standardsRoot: root });
  assert.equal(report.ok, true, JSON.stringify(report.issues));
  const ids = {};
  for (const m of manifest.methods) for (const p of [...m.inputPorts, ...m.outputPorts]) {
    assert.equal(p.acceptedTypeSets.length, 1); assert.equal(p.acceptedTypeSets[0].allowedTypes.length, 1);
    const [type] = p.acceptedTypeSets[0].allowedTypes;
    assert.equal(type.acceptsAnyFlatbuffer, undefined); assert.equal(type.wireFormat, 'flatbuffer');
    ids[`${m.methodId}.${p.portId}`] = type.fileIdentifier;
  }
  assert.deepEqual(ids, { 'plan_launches.tick': 'TICK', 'plan_launches.request': 'HREQ', 'parse_launches.response': 'HRSP',
    'parse_launches.records': '$LDM', 'parse_launches.meta': 'INGQ', 'parse_launches.report': 'FNTC' });
});

test('plans one bounded anonymous GET, its plan in CONTEXT, and refuses other access tiers', async (t) => {
  const request = await plan(t);
  const url = new URL(request.url);
  assert.equal(request.url, URL_100);
  assert.equal(url.hostname, 'll.thespacedevs.com');
  assert.equal(url.pathname, '/2.3.0/launches/upcoming/');
  assert.equal(url.searchParams.get('mode'), 'normal');
  assert.equal(url.searchParams.get('limit'), '100');
  assert.deepEqual([request.method, request.timeoutMs, request.maxBytes], ['GET', 30000, 4 * 1024 * 1024]);
  assert.deepEqual(request.headers, {});
  const job = readJob(request.context);
  assert.deepEqual(job, { schema: 'LDM.fbs', tags: { providerId: 'launch-schedule', sourceName: 'upcoming', batchId: '', sourceUrl: URL_100, contentKeyId: '',
    sourcePeer: producerPeerId, license: '', licenseUrl: 'https://thespacedevs.com/llapi', citation: CITATION, shareAlike: false }, reconcile: 'current', archive: null, provenance: null });
  assert.equal(new URL((await plan(t, nodeConfig({ launch_schedule_source: { access: 'anonymous', limit: 25 } }))).url).searchParams.get('limit'), '25');
  assert.equal((await plan(t, nodeConfig({ launch_schedule_source: { access: 'anonymous' } }))).url, URL_100, 'limit defaults to 100');
  const h = await core(t);
  for (const bad of [{}, { access: 'supporter' }, { access: 'anonymous', limit: 0 }, { access: 'anonymous', limit: 101 }, { access: 'anonymous', limit: 2.5 }, { access: 'anonymous', limit: '10' }]) {
    h.stub.config = nodeConfig({ launch_schedule_source: bad });
    const refused = await planned(h);
    assert.notEqual(refused.statusCode, 0, JSON.stringify(bad));
    assert.equal(refused.outputs.length, 0);
  }
});

test('turns each NET precision into the window it states', async (t) => {
  const { context } = await plan(t);
  const h = await core(t);
  const result = await parse(h, context, recordedBytes, 200, { headers: { 'content-type': 'application/json', etag: '"ll2"' } });
  assert.equal(result.statusCode, 0, result.errorMessage);
  assert.deepEqual(h.stub.wire, [], 'parse makes no host call');
  const rows = records(result);
  assert.equal(rows.length, 7);
  const byId = Object.fromEntries(rows.map((r) => [r.ID, r]));
  // [id, NET, earliest, latest]. Second/minute precision keeps the published
  // window; calendar precisions span the whole stated period (Gregorian
  // month lengths; Q4 = Oct-Dec; H2 = Jul-Dec).
  const expected = [
    ['7d1afb26-6f9c-429b-9ccf-29012fd1e519', '2026-09-28T12:48:59Z', '2026-09-28T12:15:00Z', '2026-09-28T13:30:00Z'],
    ['67213393-7983-4c06-8b44-b8c785a5ed79', '2026-10-01T18:18:00Z', '2026-10-01T18:18:00Z', '2026-10-01T19:16:00Z'],
    ['6b89cfc8-8880-4b5b-856c-0e547d45b639', '2026-10-05T00:00:00Z', '2026-10-05T00:00:00Z', '2026-10-05T23:59:59Z'],
    ['7bdc412b-c965-4517-a131-f57a01189803', '2026-10-01T00:00:00Z', '2026-10-01T00:00:00Z', '2026-10-31T23:59:59Z'],
    ['0b85fcca-5252-48d7-9ccb-c10b1da9d183', '2026-10-01T00:00:00Z', '2026-10-01T00:00:00Z', '2026-12-31T23:59:59Z'],
    ['e61d353c-db55-4a57-8184-0fab187231e6', '2026-07-01T00:00:00Z', '2026-07-01T00:00:00Z', '2026-12-31T23:59:59Z'],
    ['b78857c4-3b8d-4462-929e-bc76f39c0e6d', '2026-01-01T00:00:00Z', '2026-01-01T00:00:00Z', '2026-12-31T23:59:59Z'],
  ];
  for (const [id, net, earliest, latest] of expected) {
    const row = byId[id];
    assert.ok(row, id);
    assert.equal(row.NET, net, id);
    assert.deepEqual(row.EARLIEST_LAUNCH_TIMES, [earliest], id);
    assert.deepEqual(row.LATEST_LAUNCH_TIMES, [latest], id);
  }
  const starship = byId['7d1afb26-6f9c-429b-9ccf-29012fd1e519'];
  // float32 site coordinates: 1e-5 deg (about 1 m) covers the rounding.
  assert.ok(Math.abs(starship.SITE.LATITUDE - 25.99677) < 1e-5);
  assert.ok(Math.abs(starship.SITE.LONGITUDE - -97.15799) < 1e-5);
  assert.equal(starship.AGENCY_NAME, 'SpaceX');
  assert.equal(starship.ROCKET_CONFIGURATION.NAME, 'Starship V3');
  assert.equal(starship.ORBIT_TYPE, 'LEO');
  assert.equal(starship.REFERENCES, recorded.results[0].url);
  assert.deepEqual(decodeFlowNotice(out(result, 'report').payload), { kind: 'info', schema: 'LDM.fbs', providerId: 'launch-schedule', sourceName: 'upcoming',
    batchId: createHash('sha256').update(recordedBytes).digest('hex'), count: 7, reason: 'normalized', items: ['registry-count:367'], atMs: retrievedMs });
  const meta = decodeIngestRequest(out(result, 'meta').payload);
  const batch = createHash('sha256').update(recordedBytes).digest('hex');
  assert.deepEqual(meta.tags, { providerId: 'launch-schedule', sourceName: 'upcoming', batchId: batch, sourceUrl: URL_100, contentKeyId: '',
    sourcePeer: producerPeerId, license: '', licenseUrl: 'https://thespacedevs.com/llapi', citation: CITATION, shareAlike: false });
  assert.equal(meta.reconcile, 'current');
  assert.equal(meta.archive, null);
  assert.deepEqual(meta.provenance, { sourceUrl: URL_100, httpStatus: 200, etag: '"ll2"', lastModified: '', contentType: 'application/json', retrievedMs,
    parser: 'launch-schedule', parserVersion: 'launch-schedule/0.2.0', sourceSha256: batch, normalizedSha256: '', normalizedCount: 7,
    schemaCounts: { 'LDM.fbs': 7 }, warnings: [], fromCache: false, attributes: [] });
});

test('skips a launch whose precision it cannot turn into a window', async (t) => {
  const { context } = await plan(t);
  const h = await core(t);
  const body = structuredClone(recorded);
  body.results[6].net_precision = { id: 13, name: 'Decade', abbrev: 'DEC' };
  const result = await parse(h, context, body);
  assert.equal(result.statusCode, 0, result.errorMessage);
  assert.equal(records(result).length, 6);
  const report = decodeFlowNotice(out(result, 'report').payload);
  assert.equal(report.count, 6);
  assert.deepEqual(report.items, ['registry-count:367', `skipped-imprecise:${recorded.results[6].id}`]);
});

test('rejects failed or malformed responses and foreign plans atomically', async (t) => {
  const { context } = await plan(t);
  const h = await core(t);
  for (const status of [304, 429, 500, 0]) {
    const r = await parse(h, context, recorded, status);
    assert.notEqual(r.statusCode, 0); assert.equal(r.outputs.length, 0);
  }
  const broken = [
    (b) => { b.results[0].id = 'not-a-uuid'; },
    (b) => { b.results[1].window_end = '2026-10-01T18:00:00Z'; },
    (b) => { b.results[2].pad.latitude = 91; },
    (b) => { b.results[3].net = '2026-10-31'; },
    (b) => { delete b.results; },
  ];
  for (const mutate of broken) {
    const body = structuredClone(recorded);
    mutate(body);
    const result = await parse(h, context, body);
    assert.notEqual(result.statusCode, 0);
    assert.equal(result.outputs.length, 0);
  }
  const job = readJob(context);
  for (const tamper of [
    { ...job, tags: { ...job.tags, sourceUrl: 'https://other.example/' } },
    { ...job, tags: { ...job.tags, sourceUrl: URL_100.replace('limit=100', 'limit=101') } },
    { ...job, tags: { ...job.tags, sourcePeer: '' } },
    { ...job, tags: { ...job.tags, providerId: 'someone-else' } },
    { ...job, reconcile: 'duplicates' },
  ]) {
    const result = await parse(h, sizePrefixed(tamper), recorded);
    assert.notEqual(result.statusCode, 0, JSON.stringify(tamper));
    assert.equal(result.outputs.length, 0);
  }
  assert.notEqual((await parse(h, new Uint8Array(0), recorded)).statusCode, 0, 'no plan in CONTEXT');
  assert.notEqual((await parse(h, context, recorded, 200, { retrieved: 0 })).statusCode, 0, 'no retrieval time');
  assert.equal((await parse(h, sizePrefixed(job), recorded)).statusCode, 0, 'the canonical plan, re-encoded, is accepted');
  assert.equal((await parse(h, context)).statusCode, 0);
});
