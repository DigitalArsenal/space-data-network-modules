import assert from "node:assert/strict";
import fs from "node:fs";
import path from "node:path";
import test from "node:test";
import zlib from "node:zlib";
import { createRequire } from "node:module";
import { fileURLToPath, pathToFileURL } from "node:url";
import { createBrowserModuleHarness } from "space-data-module-sdk/host/browser-module";
import { validateArtifactWithStandards } from "space-data-module-sdk/compliance";

// Fixture: the first 20 lines of the real astorb.dat.gz downloaded 2026-10-12
// (sha256 ddbe380a..., Last-Modified 2026-10-12T04:43:20Z), Lowell Observatory,
// Dr. Edward Bowell (NASA grant NAG5-4741, Lowell Observatory endowment); free
// use with that attribution. Expected values below are read off the fixed
// columns of astorb.html by hand for (1) Ceres; nothing is generated by the
// module under test. The full file was also checked record for record against
// the closed-modules lowell-astorb-provider shards: 895,910 records, no field
// differs.
const require = createRequire(import.meta.url);
const sds = process.env.SPACE_DATA_STANDARDS_ROOT ?? path.dirname(require.resolve("spacedatastandards.org/package.json"));
const { ByteBuffer } = require("flatbuffers");
const { OMM } = await import(pathToFileURL(path.join(sds, "lib/js/OMM/main.js")));
const wasmPath = fileURLToPath(new URL("../dist/isomorphic/module.wasm", import.meta.url));
const manifest = JSON.parse(fs.readFileSync(new URL("../plugin-manifest.json", import.meta.url)));
const wasm = fs.readFileSync(wasmPath);
const head = fs.readFileSync(new URL("./fixtures/astorb-2026-10-12-head.dat", import.meta.url), "latin1").split("\n").filter(Boolean);
const receipt = { retrieved_at_ms: 1791800000000, producer_peer_id: "16Uiu2HAm1apfD3rAJJjgx4AC5Ms3PejRBwoqEsKpRx36uYwXuW9h" };
const RANGE = 48 * 1024 * 1024;

// A catalog-sized file: the 20 real rows, then 120,000 rows that reuse row 20's
// columns under new numbers (the module refuses a file under 100,000 rows).
function catalog(rows = 120000) {
  const filler = head[19];
  const lines = [...head];
  for (let n = 1; n <= rows; n++) lines.push(String(500000 + n).padStart(6, " ") + filler.slice(6));
  return zlib.gzipSync(Buffer.from(lines.join("\n") + "\n", "latin1"));
}
function ranges(gz, { count = 3, size = RANGE, status = 206 } = {}) {
  return Array.from({ length: count }, (_, i) => {
    const header = Buffer.alloc(8);
    header.write("$HRB");
    const a = i * size;
    if (a >= gz.length) { header.writeInt32LE(416, 4); return header; }
    header.writeInt32LE(status, 4);
    return Buffer.concat([header, gz.subarray(a, Math.min(a + size, gz.length))]);
  });
}
const input = (portId, value) => {
  const payload = value instanceof Uint8Array ? value : Buffer.from(JSON.stringify(value));
  return { portId, payload, typeRef: { wireFormat: "aligned-binary", requiredAlignment: 1, byteLength: payload.length } };
};
const decode = (result, port) => JSON.parse(Buffer.from(result.outputs.find((f) => f.portId === port).payload).toString());
async function harness(t) {
  const h = await createBrowserModuleHarness({ wasmSource: wasm, manifest, surface: "direct" });
  t.after(() => h.destroy());
  return h;
}
const job = { source_url: "https://ftp.lowell.edu/pub/elgb/astorb.dat.gz", provider_id: "lowell-astorb", source_name: "astorb-numbered" };
const parse = (h, responses, jobValue = job) =>
  h.invoke({ methodId: "parse_astorb", inputs: [input("job", jobValue), input("receipt", receipt), ...responses.map((r, i) => input(`response${i}`, r))] });
function records(result) {
  const bytes = result.outputs.find((f) => f.portId === "records").payload;
  const rows = [];
  for (let offset = 0; offset < bytes.length;) {
    const size = new DataView(bytes.buffer, bytes.byteOffset + offset, 4).getUint32(0, true) + 4;
    const frame = bytes.slice(offset, offset + size);
    assert.equal(Buffer.from(frame.slice(8, 12)).toString(), "$OMM");
    rows.push(OMM.getSizePrefixedRootAsOMM(new ByteBuffer(frame)).unpack());
    offset += size;
  }
  return rows;
}

test("the artifact satisfies the SDK contract", async () => {
  const report = await validateArtifactWithStandards({ wasmPath, manifest, standardsRoot: sds });
  assert.equal(report.ok, true, JSON.stringify(report.issues));
});

test("plans three 48 MiB ranges of the canonical Lowell file and nothing else", async (t) => {
  const h = await harness(t);
  const plan = await h.invoke({ methodId: "plan_astorb", inputs: [input("config", { access: "anonymous" })] });
  assert.equal(plan.statusCode, 0, plan.errorMessage);
  for (let i = 0; i < 3; i++) {
    const request = decode(plan, `request${i}`);
    assert.equal(request.url, `https://ftp.lowell.edu/pub/elgb/astorb.dat.gz?sdn-range=${i}`);
    assert.equal(request.headers.Range, `bytes=${i * RANGE}-${(i + 1) * RANGE - 1}`);
    assert.equal(request.responseWire, "raw-body-v1");
  }
  assert.deepEqual(decode(plan, "job"), job);
  const mirror = await h.invoke({ methodId: "plan_astorb", inputs: [input("config", { access: "anonymous", url: "https://example.org/astorb.dat.gz" })] });
  assert.notEqual(mirror.statusCode, 0);
});

test("Ceres reads as Lowell publishes it, brightest band first, with the attribution in the meta", async (t) => {
  const h = await harness(t);
  const gz = catalog();
  const third = Math.ceil(gz.length / 3);
  const responses = ranges(gz).map((r, i) => {
    const header = Buffer.alloc(8);
    header.write("$HRB");
    header.writeInt32LE(206, 4);
    return Buffer.concat([header, gz.subarray(i * third, Math.min((i + 1) * third, gz.length))]);
  });
  // A range shorter than the window is the end of the file, so data in a
  // later range means the file changed mid-retrieval: refused, never joined.
  const short = await parse(h, responses);
  assert.notEqual(short.statusCode, 0);
  assert.equal(short.outputs.length, 0);

  const result = await parse(h, ranges(gz));
  assert.equal(result.statusCode, 0, result.errorMessage);
  const rows = records(result);
  assert.equal(rows.length, 120020);
  const ceres = rows.find((r) => r.OBJECT_ID === "1");
  assert.equal(ceres.OBJECT_NAME, "Ceres");
  assert.equal(ceres.CENTER_NAME, "SUN");
  assert.equal(ceres.EPOCH, "2026-09-17T00:00:00");
  assert.equal(ceres.MEAN_ANOMALY, 295.937548);
  assert.equal(ceres.ARG_OF_PERICENTER, 73.20809);
  assert.equal(ceres.RA_OF_ASC_NODE, 80.248993);
  assert.equal(ceres.INCLINATION, 10.587505);
  assert.equal(ceres.ECCENTRICITY, 0.07975072);
  assert.equal(ceres.SEMI_MAJOR_AXIS, 2.76592189 * 149597870.7);
  assert.equal(ceres.GM, 1.3271244004127942e11);
  assert.deepEqual(ceres.USER_DEFINED_PARAMETERS.map((p) => [p.PARAM_NAME, p.PARAM_VALUE]), [["H", "3.34"], ["G", "0.15"], ["DIAMETER_KM", "848.4"]]);
  // H < 12 rows lead: the 20 real rows (all bright) come before the filler band.
  assert.deepEqual(rows.slice(0, 3).map((r) => r.OBJECT_ID), ["1", "2", "3"]);
  const meta = decode(result, "meta");
  assert.equal(meta.schema, "OMM.fbs");
  assert.equal(meta.provider_id, "lowell-astorb");
  assert.equal(meta.source_name, "astorb-numbered");
  assert.match(meta.citation, /Bowell.*NAG5-4741.*Lowell Observatory endowment/);
  assert.equal(meta.batch_id, (await import("node:crypto")).createHash("sha256").update(gz).digest("hex"));
  const report = decode(result, "report");
  assert.equal(report.epoch_min, "2026-09-17T00:00:00");
  assert.equal(report.records, 120020);
});

test("refuses a file of fewer than 100,000 numbered asteroids and a failed range", async (t) => {
  const h = await harness(t);
  const small = await parse(h, ranges(catalog(1000)));
  assert.notEqual(small.statusCode, 0);
  assert.equal(small.outputs.length, 0);
  const failed = ranges(catalog());
  failed[0].writeInt32LE(503, 4);
  const refused = await parse(h, failed);
  assert.notEqual(refused.statusCode, 0);
  assert.equal(refused.outputs.length, 0);
});
