  assert.equal(all.UPDATED_AT, "2026-10-12T10:13:20.000Z");
  assert.equal(all.PROVENANCE[0].SOURCE, "Lowell Observatory");
  assert.equal(all.PROVENANCE[0].SOURCE_URL, "https://ftp.lowell.edu/pub/elgb/astorb.dat.gz");
