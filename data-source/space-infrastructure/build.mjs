import fs from "node:fs";
import { fileURLToPath } from "node:url";
import createFlatc from "flatc-wasm/module";
import { compileModuleFromSource } from "space-data-module-sdk/compiler";
import { buildSourceModule } from "../../scripts/lib/build-source-module.mjs";

const root = fileURLToPath(new URL(".", import.meta.url));

// The roster (src/roster.json) is data; the module embeds it. src/roster_data.hpp is generated here and committed, and the E2E fails when it
// differs from roster.json.
const delimiter = "SDNROSTER";
const roster = fs.readFileSync(`${root}src/roster.json`, "utf8");
if (roster.includes(`)${delimiter}"`)) throw new Error("roster.json contains the raw-string delimiter");
fs.writeFileSync(`${root}src/roster_data.hpp`, `// Generated by build.mjs from roster.json. Do not edit.\n#pragma once\ninline const char* kRosterJson = R"${delimiter}(${roster})${delimiter}";\n`);

await buildSourceModule({
  root,
  importMeta: import.meta.url,
  compileModuleFromSource,
  createFlatc,
  families: ["SIT", "SNR", "PVN"],
  common: ["civil_time.hpp"],
  sources: ["../../files/orbit-products/src/sha256.hpp", "src/roster_data.hpp", "src/text.hpp", "src/space_infrastructure.cpp"],
  allowUndefinedImports: true, // plugin.getConfig through the typed $PIV bridge,
  // THREAD MODEL: wasi-sequential, declared, never inferred (scripts/lib/thread-model.mjs): the guest never spawns a thread.
  threadModel: "wasi-sequential",
});
