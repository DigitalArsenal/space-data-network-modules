// The NAIF retrieval module's SDK compiler lane, with the pinned OEM schema
// and reusable C++ readers assembled into one translation unit.
import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { compileModuleFromSource } from "space-data-module-sdk/compiler";
import { generateSdsHeader } from "../lowell-astorb/sds-header.mjs";

const root = fileURLToPath(new URL(".", import.meta.url));
const sourceFiles = [
  "../../propagator/sgp4/src/cpp/include/nlohmann/json.hpp",
  "../../common/civil_time.hpp",
  "../../common/horizons_vectors.hpp",
  "src/notables.hpp",
  "src/trajectory_plan.hpp",
  "src/packed_rows.hpp",
  "../../files/orbit-products/src/ephemeris_series.hpp",
  "src/oem_blocks.hpp",
  "src/deep_space_spacecraft.cpp",
];
const concatenatedHeaders = new Set(sourceFiles.map((file) => path.basename(file)));
const fragments = await Promise.all(sourceFiles.map(async (file) => {
  const text = await fs.readFile(path.resolve(root, file), "utf8");
  return `#line 1 "${file}"\n` + text
    .replace(/^\s*#pragma once\s*$/gm, "")
    .replace(/^\s*#include "([^"]+)"\s*$/gm, (line, include) =>
      concatenatedHeaders.has(path.basename(include)) ? "" : line);
}));
const manifest = JSON.parse(await fs.readFile(path.join(root, "plugin-manifest.json"), "utf8"));
const outputPath = path.join(root, "dist/isomorphic/module.wasm");
await fs.rm(path.join(root, "dist"), { recursive: true, force: true });
await fs.mkdir(path.dirname(outputPath), { recursive: true });

// The SDK and clang use TMPDIR for scratch. Keep every generated byte inside
// this package, including failed builds, without changing the SDK itself.
const scratch = await fs.mkdtemp(path.join(root, ".build-"));
const previousTmpdir = process.env.TMPDIR;
process.env.TMPDIR = scratch;
try {
  const { header, version } = await generateSdsHeader("OEM", import.meta.url);
  const result = await compileModuleFromSource({
    manifest,
    sourceCode: ["#define JSON_NOEXCEPTION 1", header, ...fragments].join("\n"),
    language: "c++",
    outputPath,
    threadModel: "wasi-sequential",
  });
  if (!result.report?.ok) throw new Error(JSON.stringify(result.report?.issues));
  const guest = path.join(root, "dist/guest-link");
  await fs.mkdir(guest, { recursive: true });
  await fs.writeFile(path.join(guest, "module-link.o"), result.guestLink.objectBytes);
  const { format, language, threadModel, symbolPrefix, methodSymbols } = result.guestLink;
  await fs.writeFile(path.join(guest, "metadata.json"), JSON.stringify({
    version: 1, format, language, threadModel, symbolPrefix, methodSymbols,
  }, null, 2) + "\n");
  await fs.copyFile(path.join(root, "plugin-manifest.json"), path.join(root, "dist/plugin-manifest.json"));
  await fs.writeFile(path.join(root, "dist/build-provenance.json"), JSON.stringify({
    spacedatastandards: version, schema: "OEM", threadModel: "wasi-sequential",
  }, null, 2) + "\n");
  console.log(`Built ${outputPath} against spacedatastandards.org@${version}`);
} finally {
  if (previousTmpdir === undefined) delete process.env.TMPDIR;
  else process.env.TMPDIR = previousTmpdir;
  await fs.rm(scratch, { recursive: true, force: true });
}
