#!/usr/bin/env python3
# Writes src/sources_small.hpp from bodies.json and the source files' own headers (GDAL geotransform, TIFF strip table).
#   python3 -I tools/small/gen-sources.py --dir <source dir holding the .tif files> --out src/sources_small.hpp
# The strip table is checked: one uncompressed 8-bit band, rows contiguous from strip0, so row r is the width bytes at strip0 + r * width.
import argparse, json, math, os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from osgeo import gdal
import tiffinfo
gdal.UseExceptions()
ap = argparse.ArgumentParser(); ap.add_argument('--dir', required=True); ap.add_argument('--out', required=True)
a = ap.parse_args()
doc = json.load(open(os.path.join(os.path.dirname(os.path.abspath(__file__)), 'bodies.json')))
def q(s): return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'
rows = []
for b in doc['bodies']:
    path = os.path.join(a.dir, b['file'])
    d = gdal.Open(path); gt = d.GetGeoTransform(); W, H = d.RasterXSize, d.RasterYSize
    t = tiffinfo.info(path)
    spp = t.get(277, [1])[0]; bps = t.get(258, [8]); comp = t.get(259, [1])[0]; so = t[273]; rps = t.get(278, [H])[0]
    bands = b.get('bands', 1)
    assert spp == bands and bps == [8] * bands and comp == 1 and rps == 1, (b['key'], 'needs uncompressed 8-bit one-row strips')
    assert bands == 1 or t.get(284, [1])[0] == 2, (b['key'], 'RGB must be planar (one plane after another)')
    assert len(so) == bands * H and all(so[i] == so[0] + i * W for i in range(len(so))), (b['key'], 'strips not contiguous')
    R = b['radius_m']; mdeg = R * math.pi / 180
    assert abs(gt[1] + gt[5]) < 1e-6 * gt[1], (b['key'], 'non-square pixels')
    lon_left = (b['clon'] + gt[0] / mdeg) % 360.0                       # literal east longitude of the left edge
    excess = W * gt[1] / mdeg - 360.0                                   # degrees the W columns span beyond a full turn (<= 0.03)
    lon_left = (lon_left + excess / 2.0) % 360.0                       # the module wraps by W columns: centre the seam error (+-excess/2)
    x0 = (lon_left - 180.0) * mdeg                                      # the module's frame: x = (lon_e - 180) * mdeg
    if x0 < -180 * mdeg - 1: x0 += 360 * mdeg
    lvl = b["max_level"]
    ratio = math.pi * R / (256 * 2 ** lvl) / gt[1]
    assert ratio >= 0.69, (b['key'], 'oversampled more than 1.45x', ratio)
    etag = b['etag'] if 'derived' not in b else '"derived:%s"' % b['derived']
    rows.append(f'''    {{{q(b["key"])}, {b["naif"]},
     {q(b["url"])},
     {q(etag)}, {W}, {H}, {so[0]},
     {gt[1]!r}, {x0!r}, {gt[3]!r}, {R!r}, {lvl},
     {q(b["dataset"])}, {q(b["epoch"])},
     {q(b["license"])}, {q(b.get("license_url", doc["usgs"]))},
     {q(b["credit"])},
     {q(b["key"])}, {q(b["body"].upper())}, {q(b["body"].upper() + " (sphere %.3f km)" % (R / 1000.0))},
     {bands}, {W * H if bands == 3 else 0}}},''')
    print(f'{b["key"]:30s} naif={b["naif"]} {W}x{H} strip0={so[0]} px={gt[1]:.3f} lon_left={lon_left:.4f} L{lvl} oversample={ratio:.2f}', file=sys.stderr)
open(a.out, 'w').write('''// THE SMALL-BODY SOURCES (generated by tools/small/gen-sources.py from tools/small/bodies.json and the files' own headers).
//
// One global equirectangular 8-bit mosaic per body, planetocentric latitude, one image row per strip, uncompressed and
// contiguous (rows follow strip0 at `width` bytes each), 0 = no data. x0_m is in the module's frame, x = (lon_e - 180) * m/deg:
// the file's left edge is at the east longitude the file's GeoTIFF states literally (clon + x0 / m per degree) - the IAU gazetteer
// scan (tools/small/orientation-scan.py) found no mirrored product among them. Mimas (USGS COG) and Titan (450 m partial over the
// 4 km global, tools/small/titan-composite.py) are read as the uncompressed strip files those tools write; `etag` is "derived:<file>"
// for them and the encode tool serves their ranges from that file.
#pragma once
#include "source.hpp"

namespace bit {

inline const Source* small_sources(size_t* count) {
    static const Source table[] = {
''' + '\n'.join(rows) + '''
    };
    *count = sizeof(table) / sizeof(table[0]);
    return table;
}

}  // namespace bit
''')
